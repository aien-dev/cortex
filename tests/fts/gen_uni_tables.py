#!/usr/bin/env python3
"""Generator (not product code) for the data tables in om/uni_fts.om.

Copies, number for number, the static tables that SQLite 3.45.0's FTS5 unicode61 tokenizer
uses (sqlite3.c from libsqlite3-sys-0.28.0):
  aFts5UnicodeBlock, aFts5UnicodeMap, aFts5UnicodeData   (sqlite3Fts5UnicodeCategory)
  aEntry{iCode,flags,nRange}, aiOff                      (sqlite3Fts5UnicodeFold)
  aDia, aChar                                            (fts5_remove_diacritic)
  sqlite3Utf8Trans1                                      (READ_UTF8, utf.c copy)
and prints Omega `const` offsets plus one text literal `qutx` of decimal values.

Usage: python3 tests/fts/gen_uni_tables.py PATH/TO/sqlite3.c
"""
import hashlib, re, sys

src = open(sys.argv[1], encoding='latin-1').read()


def body(start_pat, from_pos=0):
    i = src.index(start_pat, from_pos)
    j = src.index('{', i)
    k = src.index('};', j)
    return src[j + 1:k], k


def nums(txt):
    return [int(x) for x in re.findall(r'\b\d+\b', re.sub(r'/\*.*?\*/', '', txt, flags=re.S))]


def chars(txt):
    out = []
    for tok in txt.split(','):
        tok = tok.strip()
        if not tok:
            continue
        hib = '|HIBIT' in tok
        tok = tok.replace('|HIBIT', '')
        v = 0 if tok == "'\\0'" else ord(tok.strip("'"))
        out.append(v | (0x80 if hib else 0))
    return out


blk = nums(body('static u16 aFts5UnicodeBlock[] =')[0])
mp = nums(body('static u16 aFts5UnicodeMap[] =')[0])
dt = nums(body('static u16 aFts5UnicodeData[] =')[0])
fold_pos = src.index('static int sqlite3Fts5UnicodeFold(int c, int eRemoveDiacritic){')
ent_txt, _ = body('} aEntry[] =', fold_pos)
ent = re.findall(r'\{(\d+),\s*(\d+),\s*(\d+)\}', ent_txt)
aio = nums(body('static const unsigned short aiOff[] =', fold_pos)[0])
dia_pos = src.index('static int fts5_remove_diacritic(int c, int bComplex){')
dia = nums(body('unsigned short aDia[] =', dia_pos)[0])
ach = chars(body('unsigned char aChar[] =', dia_pos)[0])
utf_pos = src.index('static const unsigned char sqlite3Utf8Trans1[] = {')
tr = [int(x, 16) for x in re.findall(r'0x([0-9a-f]{2})', body('static const unsigned char sqlite3Utf8Trans1[] =', utf_pos)[0])]

assert len(blk) == 17 and len(mp) == len(dt) == 1765, (len(blk), len(mp), len(dt))
assert len(ent) == 163 and len(aio) == 77 and len(dia) == 126 and len(ach) == 126 and len(tr) == 64

parts = [('QUB', blk), ('QUM', mp), ('QUD', dt),
         ('QUFC', [int(e[0]) for e in ent]), ('QUFF', [int(e[1]) for e in ent]), ('QUFN', [int(e[2]) for e in ent]),
         ('QUAO', aio), ('QUDI', dia), ('QUDC', ach), ('QUTR', tr)]
print('note generated by tests/fts/gen_uni_tables.py from sqlite3.c sha256 %s (SQLite 3.45.0)'
      % hashlib.sha256(src.encode('latin-1')).hexdigest())
off = 0
allv = []
for name, vals in parts:
    print('const %s ulong %d' % (name, off))
    off += len(vals)
    allv += vals
print('const QUN ulong %d' % off)
print('text qutx "' + ' '.join(str(v) for v in allv) + '"')
