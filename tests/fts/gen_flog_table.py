#!/usr/bin/env python3
"""Generator (not product code) for the data table in om/flog.om.

Reads the 274 doubles of glibc 2.39's __log_data (ln2hi, ln2lo, poly[5], poly1[11],
tab[128]{invc,logc}) out of the exact libm.so.6 the Rust cortex-rs binary links on this
machine, at the address its `log` code loads them from (vaddr 0x78880, see disassembly of
log@@GLIBC_2.29 in evidence/fts/glibc-log.dis), and prints them as one Omega text literal
of decimal u64 bit patterns.

Usage: python3 tests/fts/gen_flog_table.py [/usr/lib/aarch64-linux-gnu/libm.so.6]
"""
import hashlib, struct, sys

path = sys.argv[1] if len(sys.argv) > 1 else '/usr/lib/aarch64-linux-gnu/libm.so.6'
blob = open(path, 'rb').read()
VA = 0x78880
phoff = struct.unpack_from('<Q', blob, 0x20)[0]
phentsize, phnum = struct.unpack_from('<HH', blob, 0x36)
for i in range(phnum):
    p_type, _f, p_off, p_va, _pa, p_fsz, _msz, _al = struct.unpack_from('<IIQQQQQQ', blob, phoff + i * phentsize)
    if p_type == 1 and p_va <= VA < p_va + p_fsz:
        vals = struct.unpack_from('<274Q', blob, p_off + VA - p_va)
        break
else:
    sys.exit('address not mapped')
assert vals[0] == 0x3fe62e42fefa3800 and vals[7] == 0xbfe0000000000000, 'unexpected __log_data layout'
print('note generated by tests/fts/gen_flog_table.py from %s sha256 %s' % (path, hashlib.sha256(blob).hexdigest()))
print('text qlgx "' + ' '.join(str(v) for v in vals) + '"')
