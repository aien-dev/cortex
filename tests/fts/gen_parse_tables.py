#!/usr/bin/env python3
"""Generator (not product code) for the parser tables in om/fts.om.

Copies the Lemon LALR tables of SQLite 3.45.0's FTS5 expression grammar (fts5parse.y as
generated into sqlite3.c): fts5yy_action, fts5yy_lookahead, fts5yy_shift_ofst,
fts5yy_reduce_ofst (stored +100, it is signed), fts5yy_default, fts5yyRuleInfoLhs and
fts5yyRuleInfoNRhs (stored negated, i.e. as the RHS length). Prints Omega `const` offsets
and one text literal `qptx`.

Usage: python3 tests/fts/gen_parse_tables.py PATH/TO/sqlite3.c
"""
import hashlib, re, sys

src = open(sys.argv[1], encoding='latin-1').read()


def arr(decl):
    i = src.index(decl)
    j = src.index('{', i)
    k = src.index('};', j)
    txt = re.sub(r'/\*.*?\*/', '', src[j + 1:k], flags=re.S)
    return [int(x) for x in re.findall(r'-?\d+', txt)]


act = arr('static const fts5YYACTIONTYPE fts5yy_action[] =')
look = arr('static const fts5YYCODETYPE fts5yy_lookahead[] =')
sh = arr('static const unsigned char fts5yy_shift_ofst[] =')
red = arr('static const signed char fts5yy_reduce_ofst[] =')
dfl = arr('static const fts5YYACTIONTYPE fts5yy_default[] =')
lhs = arr('static const fts5YYCODETYPE fts5yyRuleInfoLhs[] =')
nrhs = arr('static const signed char fts5yyRuleInfoNRhs[] =')
assert (len(act), len(look), len(sh), len(red), len(dfl), len(lhs), len(nrhs)) == (105, 121, 35, 18, 35, 28, 28)
parts = [('QPA', act), ('QPL', look), ('QPS', sh), ('QPR', [v + 100 for v in red]), ('QPD', dfl),
         ('QPH', lhs), ('QPN', [-v for v in nrhs])]
print('note generated by tests/fts/gen_parse_tables.py from sqlite3.c sha256 %s (SQLite 3.45.0)'
      % hashlib.sha256(src.encode('latin-1')).hexdigest())
off = 0
allv = []
for name, vals in parts:
    print('const %s ulong %d' % (name, off))
    off += len(vals)
    allv += vals
print('const QPT ulong %d' % off)
print('text qptx "' + ' '.join(str(v) for v in allv) + '"')
